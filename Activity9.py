x = eval(input(">> Give me the value of x: "))
y = eval(input(">> Give me the value of y: "))

print("____________________________________")
print("Relational/s: \n")

print("\tX is greater than Y: ", x > y)
print("\tX is less than Y: ", x < y)
print("\tX is greater than or equals to Y: ", x >= y)
print("\tX is less than or equals to Y: ", x <= y)
print("\tX is not equals to Y: ", x != y)
print("\tX is equals to Y: ", x == y)

print(" \n ____________________________________")

